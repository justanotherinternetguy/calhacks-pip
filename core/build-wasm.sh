#!/usr/bin/env bash
# Build the browser crypto module (crate `safety-wasm`) with wasm-pack.
#
#   core/build-wasm.sh          # → apps/mobile/public/wasm/{safety_wasm.js, safety_wasm_bg.wasm}
#   core/build-wasm.sh --test   # also builds a `--target nodejs` copy into core/target/wasm-node and
#                               #   runs crates/safety-wasm/tests/smoke.mjs against it
#
# The web build is served by Expo from `/wasm/…` (everything in apps/mobile/public lands in dist/).
# It is loaded at runtime by apps/mobile/modules/safety-native/src/wasm.ts, never bundled by Metro.
# Requires: rustup target wasm32-unknown-unknown, wasm-pack (~/.cargo/bin). wasm-pack fetches a
# wasm-bindgen-cli matching the Cargo.lock version on first run.
set -euo pipefail

CORE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$CORE_DIR/.." && pwd)"
CRATE_DIR="$CORE_DIR/crates/safety-wasm"
OUT_DIR="$REPO_DIR/apps/mobile/public/wasm"
NODE_OUT="$CORE_DIR/target/wasm-node"
WASM_PACK="${WASM_PACK:-$(command -v wasm-pack || echo "$HOME/.cargo/bin/wasm-pack")}"

log() { printf '\033[1;34m[build-wasm]\033[0m %s\n' "$*"; }

DO_TEST=0
for arg in "$@"; do
  case "$arg" in
    --test) DO_TEST=1 ;;
    -h|--help) sed -n '2,11p' "$0"; exit 0 ;;
    *) echo "unknown flag: $arg" >&2; exit 2 ;;
  esac
done

[ -x "$WASM_PACK" ] || { echo "wasm-pack not found (set WASM_PACK=...)" >&2; exit 1; }
rustup target list --installed | grep -q '^wasm32-unknown-unknown$' || rustup target add wasm32-unknown-unknown

# wasm-pack strips `--out-dir` relative paths from the crate dir; use an absolute path.
log "building web target → $OUT_DIR"
"$WASM_PACK" build --target web --release --out-dir "$OUT_DIR" --out-name safety_wasm "$CRATE_DIR"
# wasm-pack emits npm-package scaffolding we don't want in public/: a `.gitignore` containing `*`
# (which would hide the output from git), a package.json, and .d.ts files (types are hand-written in
# modules/safety-native/src/wasm.ts so tsc does not pick these up via `**/*.ts`).
rm -f "$OUT_DIR/.gitignore" "$OUT_DIR/package.json" "$OUT_DIR"/*.d.ts
# The glue JS is linted by `eslint .` in apps/mobile; mark it generated.
if ! head -1 "$OUT_DIR/safety_wasm.js" | grep -q eslint-disable; then
  { printf '/* eslint-disable */\n// Generated by wasm-pack from core/crates/safety-wasm — do not edit; run core/build-wasm.sh.\n'; cat "$OUT_DIR/safety_wasm.js"; } > "$OUT_DIR/safety_wasm.js.tmp"
  mv "$OUT_DIR/safety_wasm.js.tmp" "$OUT_DIR/safety_wasm.js"
fi
log "web build: $(du -h "$OUT_DIR/safety_wasm_bg.wasm" | cut -f1) wasm + $(du -h "$OUT_DIR/safety_wasm.js" | cut -f1) js"

if [ "$DO_TEST" = 1 ]; then
  log "building nodejs target → $NODE_OUT"
  "$WASM_PACK" build --target nodejs --release --out-dir "$NODE_OUT" --out-name safety_wasm "$CRATE_DIR"
  log "running smoke test"
  node "$CRATE_DIR/tests/smoke.mjs" "$NODE_OUT"
fi
log "done"
